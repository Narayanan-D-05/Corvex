// Copies ABIs from the Foundry build and the local deployment addresses into the app.
import { readFileSync, writeFileSync, existsSync, mkdirSync, copyFileSync } from 'node:fs'
import { resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..', '..', 'contracts')
const names = [
  ['ReopenCrossHook', 'hookAbi'],
  ['CorvexLens', 'lensAbi'],
  ['SessionPrintOracle', 'oracleAbi'],
  ['MarketStatus', 'marketAbi'],
  ['MockAggregator', 'feedAbi'],
  ['MockStockToken', 'tokenAbi'],
  ['OrderGateway', 'gatewayAbi'],
  ['SessionLedger', 'ledgerAbi'],
  ['ReopenReceiver', 'receiverAbi'],
]
let out = '// Generated by scripts/sync-contracts.mjs. Do not edit.\n'
for (const [file, exp] of names) {
  const p = resolve(root, 'out', `${file}.sol`, `${file}.json`)
  const abi = JSON.parse(readFileSync(p, 'utf8')).abi
  out += `export const ${exp} = ${JSON.stringify(abi)} as const\n`
}
const swap = resolve(root, 'out', 'PoolSwapTest.sol', 'PoolSwapTest.json')
out += `export const swapRouterAbi = ${JSON.stringify(JSON.parse(readFileSync(swap, 'utf8')).abi)} as const\n`
writeFileSync(resolve(import.meta.dirname, '..', 'lib', 'abis.ts'), out)

mkdirSync(resolve(import.meta.dirname, '..', 'public', 'deployments'), { recursive: true })
for (const f of ['local.json', 'robinhood-testnet.json', 'arb-sepolia.json', 'base-sepolia.json']) {
  const src = resolve(root, 'deployments', f)
  if (existsSync(src)) copyFileSync(src, resolve(import.meta.dirname, '..', 'public', 'deployments', f))
}
console.log('synced contracts')
